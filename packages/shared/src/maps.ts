const box = (b: MapBlock): MapCollider => ({ minX: b.x-b.width/2, maxX: b.x+b.width/2, minZ: b.z-b.depth/2, maxZ: b.z+b.depth/2 });
const definitions: Record<string, MapDefinition> = Object.fromEntries(Object.entries(layouts).map(([id, layout]) => {
  const blocks = [...layout, [0,-60,122,2,7], [0,60,122,2,7], [-60,0,2,118,7], [60,0,2,118,7]]
    .map(([x,z,width,depth,height]) => ({x,z,width,depth,height}));
  const spawns: MapSpawn[] = (['blue','red'] as const).flatMap(team => [-36,-18,0,18,36].map(x => ({x,z:team==='blue'?51:-51,team})));
  return [id, {id: id as MapId, arenaLimit:57.8, blocks, colliders:blocks.map(box), spawns}];
}));
export const getMapDefinition = (id: string): MapDefinition => definitions[id as MapId] ?? definitions.depot;
export const pointInCollider = (p: {x:number;z:number}, c: MapCollider) => p.x>=c.minX && p.x<=c.maxX && p.z>=c.minZ && p.z<=c.maxZ;
